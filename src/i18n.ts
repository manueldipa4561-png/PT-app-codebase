const DICTS: Record<Locale, Record<Key, string>> = { it, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Locale): T {
  const dict = DICTS[lang];
  return (key, vars) => {
    let s = dict[key] ?? it[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** "3 sessioni", "1 posto": plural forms through Intl.PluralRules. */
export function counted(t: T, lang: Locale, base: 'sessions' | 'left' | 'places', n: number): string {
  const form = new Intl.PluralRules(lang).select(Math.abs(n)) === 'one' ? 'one' : 'other';
  return t(`${base}.${form}` as Key, { n });
}

export const errorText = (t: T, code: ErrorCode | string) => (`error.${code}` in it ? t(`error.${code}` as Key) : t('error.generic'));

